import google.generativeai as genai
from google.generativeai.types import GenerateContentResponse, ContentDict
from PIL.Image import Image
from dotenv import load_dotenv
from ratelimit import limits, sleep_and_retry # Import rate limiting decorators

load_dotenv()
logger = logging.getLogger(__name__)

# Define constants for rate limiting (adjust as needed)
# Based on Gemini 1.5 Flash limits (check official docs for current limits)
MINUTE = 60
GEMINI_FLASH_RPM = 60 # Requests per minute for gemini-1.5-flash

class GeminiClient:
    """
    A rate-limited client for interacting with the Google Gemini API.

    Encapsulates configuration and provides methods for content generation.
    """
    def __init__(
        self,
        api_key: Optional[str] = None,
        model_name: str = "gemini-1.5-flash", # Default to flash model
    ):
        """
        Initializes the GeminiClient.

        Args:
            api_key (Optional[str]): The Google API key. If None, it attempts
                                     to load from the GEMINI_API_KEY environment
                                     variable. Defaults to None.
            model_name (str): The name of the Gemini model to use.
                              Defaults to "gemini-1.5-flash".

        Raises:
            ValueError: If the API key is not provided and cannot be found in
                        the environment variables.
        """
        resolved_api_key = api_key or os.getenv("GEMINI_API_KEY")
        if not resolved_api_key:
            raise ValueError(
                "Gemini API key is not provided via argument or "
                "GEMINI_API_KEY environment variable."
            )

        self.model_name = model_name
        self.api_key = resolved_api_key
        self.model = None # Initialize model attribute

        try:
            genai.configure(api_key=self.api_key)
            self.model = genai.GenerativeModel(self.model_name)
            logger.info(f"GeminiClient initialized with model: {self.model_name}")
            # Optional: Add model validation check here if needed
            # self._validate_model()
        except Exception as e:
            logger.error(f"Error configuring Gemini API or initializing model: {e}", exc_info=True)
            # Depending on desired behavior, could raise the error or leave self.model as None
            raise RuntimeError("Failed to initialize Gemini client.") from e

    # Apply rate limiting decorators
    @sleep_and_retry
    @limits(calls=GEMINI_FLASH_RPM, period=MINUTE)
    def analyze(self, prompt: str, image: Optional[Image] = None) -> str:
        """
        Analyzes text or text and image content using the configured Gemini model.

        Handles API calls with rate limiting and retries.

        Args:
            prompt: The text prompt to send to the Gemini model.
            image: An optional PIL Image object to include with the prompt. Defaults to None.

        Returns:
            The text content generated by the Gemini model, or an error message string
            if analysis fails. Returns "Client not initialized" if the model
            failed to initialize during __init__.
        """
        if not self.model:
             logger.error("Gemini model was not initialized successfully. Cannot analyze.")
             return "Analysis failed: Gemini client not initialized."

        try:
            content: list[Union[str, Image]]
            if image:
                content = [prompt, image]
                logger.debug(f"Sending prompt (len={len(prompt)}) and image to {self.model_name}.")
            else:
                content = [prompt]
                logger.debug(f"Sending prompt (len={len(prompt)}) to {self.model_name}.")

            # Make the API call using the initialized model instance
            response: GenerateContentResponse = self.model.generate_content(content)

            # --- Response Handling (incorporating checks) ---
            if not response.candidates:
                feedback = getattr(response, 'prompt_feedback', None)
                block_reason = getattr(feedback, 'block_reason', 'Unknown')
                safety_ratings = getattr(feedback, 'safety_ratings', 'N/A')
                logger.warning(
                    f"Gemini model ({self.model_name}) did not return candidates. "
                    f"Block reason: {block_reason}. Safety: {safety_ratings}"
                )
                return f"Analysis failed: No response generated (Block reason: {block_reason})."

            # Access text safely
            candidate = response.candidates[0]
            if candidate.content and candidate.content.parts:
                 full_text = "".join(part.text for part in candidate.content.parts if hasattr(part, 'text'))
                 logger.debug(f"Gemini response received (from parts): {full_text[:100]}...")
                 # Check for empty text even if parts exist
                 if not full_text.strip():
                      logger.warning(f"Gemini response parts were empty for prompt: {prompt[:100]}...")
                      return "Analysis failed: Empty response content."
                 return full_text
            # Fallback check for response.text (might exist on simpler responses or errors)
            elif hasattr(response, 'text') and response.text:
                 logger.debug(f"Gemini response received (.text): {response.text[:100]}...")
                 return response.text
            else:
                 finish_reason = getattr(candidate, 'finish_reason', 'UNKNOWN')
                 logger.warning(
                    f"Gemini response candidate exists but has no text parts or .text attribute. "
                    f"Finish reason: {finish_reason}. Content: {getattr(candidate, 'content', 'N/A')}"
                 )
                 return f"Analysis failed: No text content in response (Finish reason: {finish_reason})."

        except Exception as e:
            # Catch potential API errors (e.g., InvalidArgument, RateLimitExceeded - though handled by decorator)
            # and other unexpected exceptions during the call.
            logger.error(f"Error during Gemini API call ({self.model_name}): {str(e)}", exc_info=True)
            return f"Analysis failed due to API error: {str(e)}"

